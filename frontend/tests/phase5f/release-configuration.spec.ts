import { test, expect } from "@playwright/test";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

test("startup release flags govern upload to quota and the normal Assistant journey", async ({ page, request }) => {
  const api = "http://127.0.0.1:3101";
  const runtime = await (await request.get(api + "/_test/release")).json();
  expect(runtime.engine).toBe("compact_exhaustive");
  expect(runtime.profile).toBe("experimental_compatibility_decision_v1");
  expect(runtime.evaluator).toBe("SuitabilityRequestEvaluator");
  await request.post(api + "/_test/quota/setup/99");
  const login = await request.post(api + "/api/v1/account/login", { data: { email: "quota@example.test", password: "Quota-test-password-123" } });
  const token = (await login.json()).access_token;
  await page.addInitScript(t => sessionStorage.setItem("smart_wardrobe_access_token", t), token);
  await page.goto("/extract");
  await expect(page.getByRole("region", { name: "Wardrobe capacity" })).toContainText("99 / 100");
  const image = await page.evaluate(() => {
    const canvas = document.createElement("canvas"); canvas.width = 256; canvas.height = 256;
    canvas.getContext("2d")!.fillRect(0, 0, 256, 256); return canvas.toDataURL("image/png").split(",")[1];
  });
  await page.getByLabel("Wardrobe image").setInputFiles({ name: "synthetic.png", mimeType: "image/png", buffer: Buffer.from(image, "base64") });
  await expect(page).toHaveURL(/\/extract\/results\?job=/);
  await page.getByText("Edit details and review image", { exact: true }).click();
  await page.getByRole("combobox", { name: "Category", exact: true }).selectOption("vest_dress");
  await page.getByLabel("Primary colour", { exact: true }).fill("blue");
  await page.getByRole("combobox", { name: "Style", exact: true }).selectOption("vintage");
  await page.getByRole("button", { name: "Accept candidate", exact: true }).click();
  await expect(page.getByText("Only these selected garments will be saved.", { exact: false })).toBeVisible();
  await page.getByRole("button", { name: "Save selected garments", exact: true }).click();
  await expect(page).toHaveURL(/\/wardrobe$/);
  await expect(page.getByRole("region", { name: "Wardrobe capacity" })).toContainText("100 / 100");
  await page.goto("/assistant");
  await page.getByLabel("What would you like to wear?").fill("Suggest an outfit for campus");
  let pending = page.waitForResponse(r => r.url().includes("pipeline=integrated") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Suggest an outfit", exact: true }).click();
  const unknown = await (await pending).json(); expect(unknown.outcome).toBe("InsufficientEvidence");
  await page.getByRole("button", { name: "New Chat", exact: true }).click();
  await page.getByLabel("What would you like to wear?").fill("Suggest a vintage outfit");
  pending = page.waitForResponse(r => r.url().includes("pipeline=integrated") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Suggest an outfit", exact: true }).click();
  const response = await pending; const selected = await response.json();
  expect(response.status()).toBe(201); expect(selected.outcome).toBe("Selected");
  expect(selected.items).toHaveLength(1); expect(selected.total_score).toBe(.7);
  expect(selected.provenance.scoring_profile).toBe(runtime.profile);
  expect(selected.provenance.request_evaluator).toBe(runtime.evaluator);
  await expect(page.getByTestId("recommendation-result")).toBeVisible();
  const quota = await (await request.get(api + "/api/v1/wardrobe/quota", { headers: { Authorization: `Bearer ${token}` } })).json();
  expect(quota.used).toBe(100);
  writeFileSync(resolve("../storage/verification/phase5f2e3j12/normal-journey.json"), JSON.stringify({ runtime, unknown, selected, quota }, null, 2));
});
