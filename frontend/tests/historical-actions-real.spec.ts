test("real historical save and visualisation preserve the completed interaction",async({page,request})=>{
  const api="http://127.0.0.1:3101/api/v1";
  const auth=await request.post(api+"/account/login",{data:{email:"browser-other@example.test",password:"Browser-test-password-123"}});
  expect(auth.ok()).toBeTruthy();
  const token=(await auth.json()).access_token; const headers={Authorization:`Bearer ${token}`};
  await page.addInitScript(value=>sessionStorage.setItem("smart_wardrobe_access_token",value),token);
  await page.goto("/extract");
  await page.getByLabel("Wardrobe image").setInputFiles({name:"synthetic-history-dress.png",mimeType:"image/png",buffer:image});
  await page.waitForURL("**/extract/results?job=**");
  const candidate=page.getByRole("article",{name:/Candidate/}).first();
  await candidate.getByText("Edit details and review image",{exact:true}).click();
  await candidate.getByLabel("Category",{exact:true}).selectOption("vest_dress");
  await candidate.getByLabel("Garment name").fill("Historical source dress");
  await candidate.getByLabel("Style").selectOption("vintage");
  const review=page.waitForResponse(r=>r.url().endsWith("/review") && r.request().method()==="POST");
  await candidate.getByRole("button",{name:/Accept/}).click(); expect((await review).status()).toBe(200);
  const confirm=page.waitForResponse(r=>r.url().endsWith("/confirm") && r.request().method()==="POST");
  await page.getByRole("button",{name:"Save selected garments",exact:true}).click(); expect((await confirm).status()).toBe(201);
  await page.waitForURL("**/wardrobe");
  await page.goto("/assistant");
  await page.getByLabel("What would you like to wear?").fill("Suggest an outfit with vintage style");
  await page.getByRole("button",{name:"Suggest an outfit",exact:true}).click();
  await expect(page.getByTestId("recommendation-result")).toBeVisible();
  const chats=await (await request.get(api+"/chats",{headers})).json(); expect(chats.total).toBe(1);
  const chat=chats.items[0].chat_id;
  const before=await (await request.get(api+"/chats/"+chat,{headers})).json();
  const rec=before.recommendation; const garment=rec.items[0].garment_id;
  let generationPosts=0;
  page.on("request",r=>{if(r.method()==="POST" && /\/recommendations(?:\?|$|\/homepage)/.test(r.url())) generationPosts++;});
  await page.goto("/history/"+chat);
  const save=page.waitForResponse(r=>r.url().endsWith("/save-as-outfit") && r.request().method()==="POST");
  await page.getByRole("button",{name:"Save as outfit",exact:true}).dblclick();
  const savedResponse=await save; expect(savedResponse.status()).toBe(201); const outfit=await savedResponse.json();
  await expect(page.getByRole("button",{name:"Saved as outfit",exact:true})).toBeDisabled();
  const repeats=await Promise.all(Array.from({length:4},()=>request.post(api+`/recommendations/${rec.id}/save-as-outfit`,{headers,data:{}})));
  for(const repeat of repeats){expect(repeat.status()).toBe(201);expect((await repeat.json()).id).toBe(outfit.id);}
  expect((await (await request.get(api+`/recommendations/${rec.id}/saved-outfit`,{headers})).json()).saved).toBe(true);
  expect(await (await request.get(api+"/chats/"+chat,{headers})).json()).toEqual(before);
  const outfits=await (await request.get(api+"/wardrobe/outfits",{headers})).json();
  expect(outfits.some((o:{id:string})=>o.id===outfit.id)).toBe(true);
  await page.reload(); await expect(page.getByRole("button",{name:"Saved as outfit",exact:true})).toBeDisabled();
  const person=await request.post(api+"/media/person-images",{headers,multipart:{file:{name:"synthetic-person.png",mimeType:"image/png",buffer:image}}});
  expect(person.ok()).toBeTruthy();
  await page.getByRole("link",{name:"Visualise outfit",exact:true}).click();
  await expect(page).toHaveURL(new RegExp("/try-on\\?recommendation="+rec.id));
  const creation=page.waitForResponse(r=>r.url().endsWith("/visualisations") && r.request().method()==="POST");
  await page.getByRole("button",{name:"Create visualisation",exact:true}).dblclick();
  const created=await creation; expect(created.status()).toBe(202); const visual=await created.json();
  expect(created.request().postDataJSON().recommendation_id).toBe(rec.id);
  await expect(page.getByRole("button",{name:"Download output",exact:true})).toBeEnabled({timeout:60000});
  expect((await (await request.get(api+"/visualisations/"+visual.id,{headers})).json()).status).toBe("completed");
  expect(await (await request.get(api+"/chats/"+chat,{headers})).json()).toEqual(before);
  expect((await (await request.get(api+"/chats",{headers})).json()).total).toBe(1);
  expect(generationPosts).toBe(0);
  const foreign=(await (await request.post(api+"/account/login",{data:{email:"browser-owner@example.test",password:"Browser-test-password-123"}})).json()).access_token;
  const other={Authorization:`Bearer ${foreign}`};
  expect((await request.get(api+"/chats/"+chat,{headers:other})).status()).toBe(404);
  expect((await request.get(api+`/recommendations/${rec.id}/saved-outfit`,{headers:other})).status()).toBe(404);
  expect((await request.post(api+`/recommendations/${rec.id}/save-as-outfit`,{headers:other,data:{}})).status()).toBe(404);
  expect((await request.post(api+"/visualisations/prepare",{headers:other,data:{recommendation_id:rec.id}})).status()).toBe(404);
  expect((await request.delete(api+"/wardrobe/outfits/"+outfit.id,{headers})).status()).toBe(204);
  expect((await request.delete(api+"/wardrobe/garments/"+garment,{headers})).status()).toBe(204);
  await page.goto("/history/"+chat);
  await expect(page.getByText("Historical source dress",{exact:true})).toBeVisible();
  await expect(page.getByText("Unavailable for current use")).toBeVisible();
  await expect(page.getByRole("button",{name:"Save as outfit",exact:true})).toHaveCount(0);
  expect((await request.post(api+`/recommendations/${rec.id}/save-as-outfit`,{headers,data:{}})).status()).toBe(409);
  expect((await request.post(api+"/visualisations/prepare",{headers,data:{recommendation_id:rec.id}})).status()).toBe(409);
  const after=await (await request.get(api+"/chats/"+chat,{headers})).json();
  expect(after.request_text).toBe(before.request_text);
  expect(after.recommendation.score_metadata).toEqual(before.recommendation.score_metadata);
  expect(after.recommendation.provenance).toEqual(before.recommendation.provenance);
});
